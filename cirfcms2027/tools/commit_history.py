#!/usr/bin/env python3
"""Write `docs/commit-history.md`: every commit that touched this directory.

    python3 tools/commit_history.py

One row per commit, oldest first: date, short hash, subject, and the files it
changed under `cirfcms2027/`. Regenerate after new commits; the file is a
convenience for readers without git, and git itself remains the record.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "commit-history.md"


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, check=True,
                          capture_output=True, text=True).stdout


def main() -> None:
    log = git("log", "--reverse", "--date=short", "--name-only",
              "--format=@@%h|%ad|%s", "--", ".")
    rows, cur = [], None
    for line in log.splitlines():
        if line.startswith("@@"):
            if cur:
                rows.append(cur)
            h, d, s = line[2:].split("|", 2)
            cur = {"hash": h, "date": d, "subject": s, "files": []}
        elif line.strip() and cur is not None:
            cur["files"].append(line.strip())
    if cur:
        rows.append(cur)
    L = ["# Commit history of `cirfcms2027/`", "",
         f"{len(rows)} commits, {rows[0]['date']} to {rows[-1]['date']}, oldest first. "
         "Generated by `tools/commit_history.py` from the branch "
         "`claude/lucid-feynman-bqpmqw`; regenerate after new commits.", "",
         "| # | date | commit | subject | files changed |", "|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        files = [f.replace("cirfcms2027/", "", 1) for f in r["files"]]
        shown = ", ".join(f"`{f}`" for f in files[:6])
        if len(files) > 6:
            shown += f", and {len(files) - 6} more"
        subj = r["subject"].replace("|", "\\|")
        L.append(f"| {i} | {r['date']} | `{r['hash']}` | {subj} | {shown} |")
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT} ({len(rows)} commits)")


if __name__ == "__main__":
    main()
